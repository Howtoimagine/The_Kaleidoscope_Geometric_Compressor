"""
Vector quantization: KGC Leech-VQ vs FAISS - the industry standard.

Product Quantization (Jegou et al. 2011), as implemented in FAISS, is
THE industry-standard method for compressing high-dimensional vectors -
it is the literal "other thing that does the same thing" as our Leech
lattice VQ. Both take a set of vectors and compress each to a few bits;
both are judged by the same two metrics:

    reconstruction MSE      (rate-distortion, protocol-independent)
    recall@10               (does the compressed DB return the true
                             nearest neighbours of held-out queries)

versus bits/vector (the rate). This is the standard ANN-compression
benchmark methodology.

Competitors (all via FAISS):
    PQ    Product Quantization, M subquantizers x nbits
    OPQ   PQ preceded by a learned rotation (OPQ = PQ + incoherence)
    SQ    Scalar Quantization (per-dimension int8/int6/int4)
    KGC   this repo: exact Leech lattice VQ (+/- Hadamard incoherence)

Data: real 384-dim sentence embeddings (all-MiniLM-L6-v2 over WikiText),
generated by gen_embeddings.py. 384 = 24*16, native for both the Leech
24-block and PQ subquantizers.

MEASURED FRONTIER (real embeddings, recall@10 vs exact top-10):

    method            bits/vec   recon MSE   recall@10
    PQ  M=32           256        6.5e-4      0.732
    PQ  M=48           384        4.4e-4      0.762
    OPQ M=48           384        3.9e-4      0.815
    OPQ M=64           512        2.6e-4      0.841
    KGC Leech s=0.75   733        3.0e-4      0.848
    KGC Leech s=1.5   1049        7.6e-5      0.924
    SQ4               1536        4.1e-5      0.942
    KGC Leech s=3.0   1413        1.9e-5      0.960
    KGC Leech s=5.0   1691        6.8e-6      0.976
    SQ6               2304        2.3e-6      0.987
    SQ8               3072        1.4e-7      0.995

HONEST READING. KGC's fixed-lattice VQ sits BETWEEN scalar quantization
and learned Product Quantization:
  * It BEATS scalar quantization (SQ) - e.g. 0.960 recall @ 1413 bits vs
    SQ4's 0.942 @ 1536 bits (better recall, fewer bits). The Leech
    lattice's superior 24-D packing beats the axis-aligned scalar grid.
  * It LOSES to PQ/OPQ in the aggressive-compression regime PQ is built
    for - OPQ hits 0.841 recall at 512 bits; KGC needs ~730+ bits to
    match. PQ/OPQ LEARN their codebook (k-means centroids placed where
    the data actually lives, plus a learned rotation); KGC uses the
    FIXED lattice and cannot concentrate its bits on the data
    distribution the same way.

The gap IS the value of a learned, data-adaptive codebook - exactly what
the consolidation / Resonant-Quantization machinery (ARCHITECTURE.md)
would add to the lattice. This benchmark says precisely where the system
stands (a strong high-fidelity quantizer, not yet a PQ replacement for
billion-scale ANN) and what would close the distance.

Caveats: KGC rate is the empirical entropy of its index streams (what an
entropy coder achieves); PQ rate is fixed M*nbits. Recall is
reconstruct-then-search for every method (identical protocol; PQ's native
asymmetric search would lift its recall somewhat, but it already wins on
rate). DB ~1-1.5k vectors, so recall carries a little noise, but the
frontier ordering is stable across runs.

truth_status: standard_vector_quantization_measurement
"""

import sys
import time
from pathlib import Path

import numpy as np

_root = Path(__file__).resolve().parent.parent
import importlib.util

if "e8zip" not in sys.modules:
    _spec = importlib.util.spec_from_file_location(
        "e8zip", _root / "__init__.py", submodule_search_locations=[str(_root)]
    )
    _mod = importlib.util.module_from_spec(_spec)
    sys.modules["e8zip"] = _mod
    _spec.loader.exec_module(_mod)

import faiss  # noqa: E402

from e8zip.core.leech_lattice import (  # noqa: E402
    batch_nearest_leech_point,
    leech_index_decompose,
)
from e8zip.core import transforms  # noqa: E402


def recall_at_k(db_hat, Q, gt, k=10):
    """Reconstruct-then-search recall@k: search compressed DB with full queries."""
    index = faiss.IndexFlatL2(db_hat.shape[1])
    index.add(np.ascontiguousarray(db_hat.astype(np.float32)))
    _, idx = index.search(np.ascontiguousarray(Q.astype(np.float32)), k)
    hits = sum(len(set(idx[i]) & set(gt[i])) for i in range(len(Q)))
    return hits / (len(Q) * k)


def mse(a, b):
    return float(((a.astype(np.float64) - b.astype(np.float64)) ** 2).mean())


def kgc_leech_vq(DB, scale, transform="none", seed=42):
    """Per-vector Leech VQ. Returns (reconstructed_DB, bits_per_vector)."""
    N, D = DB.shape
    assert D % 24 == 0
    flat = DB.astype(np.float64).ravel()
    if transform == "hadamard":
        # incoherence over 128-wide rows (like OPQ's rotation)
        hdim = 128
        padt = (-flat.size) % hdim
        rows = np.concatenate([flat, np.zeros(padt)]).reshape(-1, hdim)
        inc = transforms.forward(rows, "hadamard", seed).ravel()
    else:
        inc = flat
    sigma = inc.std() or 1.0
    x = inc / sigma * scale
    padb = (-x.size) % 24
    xb = np.concatenate([x, np.zeros(padb)]).reshape(-1, 24)
    pts, _, _ = batch_nearest_leech_point(xb)
    xr = pts.ravel()[: inc.size] / scale * sigma
    if transform == "hadamard":
        back = transforms.inverse(xr.reshape(-1, 128), "hadamard", seed).ravel()[: flat.size]
    else:
        back = xr[: flat.size]
    db_hat = back.reshape(N, D)

    # rate: empirical entropy of the index streams
    g, c, z = leech_index_decompose(pts)

    def H(a):
        a = np.asarray(a).ravel()
        _, cnt = np.unique(a, return_counts=True)
        p = cnt / cnt.sum()
        return float(-(p * np.log2(p)).sum())

    zz = lambda v: np.where(v >= 0, 2 * v, -2 * v - 1)
    bits_per_block = H(g) + H(c) + sum(H(zz(z[:, j])) for j in range(24))
    bits_per_vec = bits_per_block * (D // 24)
    return db_hat, bits_per_vec


def main():
    SCR = sys.argv[1] if len(sys.argv) > 1 else "emb384.npy"
    E = np.load(SCR).astype(np.float32)
    rng = np.random.default_rng(0)
    rng.shuffle(E)
    nq = 500
    Q, DB = E[:nq], E[nq : nq + 1500]
    D = DB.shape[1]
    print(f"DB={DB.shape}  queries={Q.shape}  dim={D}\n")

    # exact ground-truth top-10
    gtindex = faiss.IndexFlatL2(D)
    gtindex.add(np.ascontiguousarray(DB))
    _, gt = gtindex.search(np.ascontiguousarray(Q), 10)

    results = []  # (name, bits/vec, mse, recall@10)

    # ---- FAISS PQ / OPQ / SQ ----
    faiss_specs = [
        ("PQ M=32 nbits=8", lambda: faiss.IndexPQ(D, 32, 8)),
        ("PQ M=48 nbits=8", lambda: faiss.IndexPQ(D, 48, 8)),
        ("PQ M=64 nbits=8", lambda: faiss.IndexPQ(D, 64, 8)),
        ("PQ M=96 nbits=4", lambda: faiss.IndexPQ(D, 96, 4)),
        ("OPQ M=48 nbits=8", lambda: faiss.index_factory(D, "OPQ48,PQ48")),
        ("OPQ M=64 nbits=8", lambda: faiss.index_factory(D, "OPQ64,PQ64")),
        ("SQ8", lambda: faiss.IndexScalarQuantizer(D, faiss.ScalarQuantizer.QT_8bit)),
        ("SQ6", lambda: faiss.IndexScalarQuantizer(D, faiss.ScalarQuantizer.QT_6bit)),
        ("SQ4", lambda: faiss.IndexScalarQuantizer(D, faiss.ScalarQuantizer.QT_4bit)),
    ]
    bits_map = {
        "PQ M=32 nbits=8": 256, "PQ M=48 nbits=8": 384, "PQ M=64 nbits=8": 512,
        "PQ M=96 nbits=4": 384, "OPQ M=48 nbits=8": 384, "OPQ M=64 nbits=8": 512,
        "SQ8": 8 * D, "SQ6": 6 * D, "SQ4": 4 * D,
    }
    for name, mk in faiss_specs:
        try:
            idx = mk()
            idx.train(np.ascontiguousarray(DB))
            idx.add(np.ascontiguousarray(DB))
            db_hat = idx.reconstruct_n(0, DB.shape[0])
            results.append((name, bits_map[name], mse(DB, db_hat), recall_at_k(db_hat, Q, gt)))
            print(f"  {name:20s} done", flush=True)
        except Exception as e:
            print(f"  {name:20s} FAILED: {e}")

    # ---- KGC Leech VQ (sweep scale to trace the full rate-distortion
    # frontier, from PQ's aggressive regime up to near-lossless) ----
    for tf in ("none", "hadamard"):
        for scale in (0.75, 1.5, 3.0, 5.0):
            t0 = time.time()
            db_hat, bpv = kgc_leech_vq(DB, scale, transform=tf)
            tag = f"KGC Leech s={scale} {tf[:4]}"
            results.append((tag, bpv, mse(DB, db_hat), recall_at_k(db_hat, Q, gt)))
            print(f"  {tag:20s} {bpv:5.0f} b/vec ({time.time()-t0:.0f}s)", flush=True)

    # ---- report, sorted by rate ----
    print(f"\n{'method':22s} {'bits/vec':>9s} {'recon MSE':>12s} {'recall@10':>10s}")
    for name, bpv, m, r in sorted(results, key=lambda x: x[1]):
        tag = "*" if name.startswith("KGC") else " "
        print(f"{tag}{name:21s} {bpv:9.0f} {m:12.4e} {r:10.3f}")
    print("\n(* = this repo. Compare KGC vs PQ/OPQ at matched bits/vec: "
          "lower MSE and higher recall@10 at equal rate = better.)")


if __name__ == "__main__":
    main()
